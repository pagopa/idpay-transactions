package it.gov.pagopa.idpay.transactions.persistence.sql;

import static org.junit.jupiter.api.Assertions.assertFalse;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.file.Files;
import java.nio.file.Path;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.ValueSource;

/**
 * Guards AC5: the four flows that may create a new reward batch must rely solely on
 * {@code RewardBatchFactory} for id generation and must never reassign the generated id.
 */
class RewardBatchIdAssignmentArchitectureTest {

    private static final String SOURCE_ROOT = "src/main/java/it/gov/pagopa/idpay/transactions/persistence/sql/";

    @ParameterizedTest
    @ValueSource(strings = {
            "SqlInvoicedTransactionAssignmentAdapter.java",
            "SqlMerchantTransactionPostponementAdapter.java",
            "SqlSuspendedTransactionReassignmentAdapter.java",
            "SqlPaymentRewardBatchImpactAdapter.java"
    })
    void shouldNotAssignRewardBatchIdOutsideTheFactory(String sourceFileName) {
        String source = readSource(sourceFileName);

        assertFalse(
                source.contains("UUID.randomUUID()"),
                sourceFileName + " must not generate reward batch ids with UUID.randomUUID()"
        );
        assertFalse(
                source.contains(".setId("),
                sourceFileName + " must not overwrite the reward batch id generated by RewardBatchFactory"
        );
    }

    private static String readSource(String sourceFileName) {
        try {
            return Files.readString(Path.of(SOURCE_ROOT + sourceFileName));
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }
}
